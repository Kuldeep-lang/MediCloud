from datetime import date

from sqlalchemy import Index, Sequence, String, Text, text
from sqlalchemy.orm import Mapped, mapped_column

from app.core.timeutils import local_today
from app.db.base import Base, IdMixin, TimestampMixin, str_enum
from app.models.enums import BloodGroup, Gender

patient_code_seq = Sequence("patient_code_seq", metadata=Base.metadata)


class Patient(IdMixin, TimestampMixin, Base):
    __tablename__ = "patients"
    __table_args__ = (
        Index("ix_patients_name", "last_name", "first_name"),
        # Trigram indexes make ILIKE '%term%' searches index-assisted.
        Index(
            "ix_patients_first_name_trgm",
            "first_name",
            postgresql_using="gin",
            postgresql_ops={"first_name": "gin_trgm_ops"},
        ),
        Index(
            "ix_patients_last_name_trgm",
            "last_name",
            postgresql_using="gin",
            postgresql_ops={"last_name": "gin_trgm_ops"},
        ),
    )
    __mapper_args__ = {"eager_defaults": True}  # fetch patient_code via RETURNING

    # Human-readable Patient ID, e.g. MCP-000123, generated by the database.
    patient_code: Mapped[str] = mapped_column(
        String(20),
        unique=True,
        server_default=text("'MCP-' || lpad(nextval('patient_code_seq')::text, 6, '0')"),
    )
    first_name: Mapped[str] = mapped_column(String(60))
    last_name: Mapped[str] = mapped_column(String(60))
    date_of_birth: Mapped[date]
    gender: Mapped[Gender] = mapped_column(str_enum(Gender, "gender", 10))
    phone: Mapped[str] = mapped_column(String(20), index=True)
    email: Mapped[str | None] = mapped_column(String(255), index=True)
    address: Mapped[str | None] = mapped_column(Text)
    blood_group: Mapped[BloodGroup | None] = mapped_column(str_enum(BloodGroup, "blood_group", 3))
    emergency_contact_name: Mapped[str | None] = mapped_column(String(120))
    emergency_contact_phone: Mapped[str | None] = mapped_column(String(20))
    allergies: Mapped[str | None] = mapped_column(Text)

    @property
    def full_name(self) -> str:
        return f"{self.first_name} {self.last_name}"

    @property
    def age(self) -> int:
        today = local_today()
        dob = self.date_of_birth
        return today.year - dob.year - ((today.month, today.day) < (dob.month, dob.day))

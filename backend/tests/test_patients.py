"""Patient registration, validation, search, update and medical history."""

from datetime import timedelta

from app.core.timeutils import local_today
from app.models.enums import AppointmentStatus

PAYLOAD = {
    "first_name": "Meera",
    "last_name": "Pillai",
    "date_of_birth": "1985-03-14",
    "gender": "female",
    "phone": "+91 9988776655",
    "email": "Meera.Pillai@Example.com",
    "blood_group": "B+",
    "address": "12 Lake Road, Kochi",
    "emergency_contact_name": "Suresh Pillai",
    "emergency_contact_phone": "+91 9988776600",
}


def test_register_patient(client, receptionist_headers):
    response = client.post("/api/v1/patients", headers=receptionist_headers, json=PAYLOAD)
    assert response.status_code == 201
    body = response.json()
    assert body["patient_code"] == "MCP-000001"  # generated by a DB sequence
    assert body["full_name"] == "Meera Pillai"
    assert body["email"] == "meera.pillai@example.com"
    assert body["age"] >= 40


def test_patient_codes_are_sequential(client, receptionist_headers):
    codes = [
        client.post("/api/v1/patients", headers=receptionist_headers, json=PAYLOAD).json()[
            "patient_code"
        ]
        for _ in range(3)
    ]
    assert codes == ["MCP-000001", "MCP-000002", "MCP-000003"]


def test_patient_validation(client, receptionist_headers):
    future = (local_today() + timedelta(days=1)).isoformat()
    cases = [
        {"date_of_birth": future},
        {"blood_group": "C+"},
        {"phone": "call me"},
        {"email": "not-an-email"},
        {"gender": "unknown"},
        {"first_name": ""},
    ]
    for override in cases:
        response = client.post(
            "/api/v1/patients", headers=receptionist_headers, json=PAYLOAD | override
        )
        assert response.status_code == 422, override


def test_search_by_name_code_and_phone(client, factory, receptionist_headers):
    target = factory.patient(first_name="Zara", last_name="Sheikh", phone="+91 9000011111")
    factory.patient(first_name="Other", last_name="Person")
    for term in ("zara", "Zara Sheikh", target.patient_code, "9000011111"):
        result = client.get(
            "/api/v1/patients", headers=receptionist_headers, params={"search": term}
        ).json()
        assert [p["id"] for p in result["items"]] == [target.id], term


def test_search_wildcards_are_escaped(client, factory, receptionist_headers):
    factory.patient()
    factory.patient()
    result = client.get("/api/v1/patients", headers=receptionist_headers, params={"search": "%"})
    assert result.json()["total"] == 0  # '%' is literal, not "match everything"


def test_pagination_envelope(client, factory, receptionist_headers):
    for _ in range(5):
        factory.patient()
    page = client.get(
        "/api/v1/patients", headers=receptionist_headers, params={"page": 2, "page_size": 2}
    ).json()
    assert page["total"] == 5
    assert page["page"] == 2
    assert len(page["items"]) == 2


def test_update_patient(client, factory, receptionist_headers):
    patient = factory.patient()
    response = client.patch(
        f"/api/v1/patients/{patient.id}",
        headers=receptionist_headers,
        json={"phone": "+91 9111111111", "allergies": "Penicillin", "first_name": None},
    )
    assert response.status_code == 200
    body = response.json()
    assert body["phone"] == "+91 9111111111"
    assert body["allergies"] == "Penicillin"
    assert body["first_name"] == "Ravi"  # required fields cannot be cleared


def test_unknown_patient_returns_404(client, receptionist_headers):
    response = client.get("/api/v1/patients/999", headers=receptionist_headers)
    assert response.status_code == 404
    assert response.json() == {"detail": "Patient 999 not found"}


def test_history_is_redacted_for_receptionists(client, factory, receptionist_headers, doctor_ctx):
    doctor, doctor_headers = doctor_ctx
    patient = factory.patient()
    appt = factory.appointment(patient, doctor, status=AppointmentStatus.COMPLETED)
    appt.diagnosis = "Acute bronchitis"
    factory.db.commit()

    clinical = client.get(f"/api/v1/patients/{patient.id}/history", headers=doctor_headers)
    assert clinical.json()["appointments"][0]["diagnosis"] == "Acute bronchitis"
    assert clinical.json()["clinical_details_redacted"] is False

    desk = client.get(f"/api/v1/patients/{patient.id}/history", headers=receptionist_headers)
    assert desk.json()["appointments"][0]["diagnosis"] is None
    assert desk.json()["clinical_details_redacted"] is True


def test_pharmacist_can_read_but_not_register(client, factory, pharmacist_headers):
    factory.patient()
    assert client.get("/api/v1/patients", headers=pharmacist_headers).status_code == 200
    assert (
        client.post("/api/v1/patients", headers=pharmacist_headers, json=PAYLOAD).status_code == 403
    )

"""Generate k8s/01-secrets.yaml (git-ignored) with strong random secrets.

Usage (from the repository root, any Python 3.10+, standard library only):
    python scripts/k8s_secrets.py                       # random secrets, demo password Demo@12345
    python scripts/k8s_secrets.py --demo-password XYZ   # choose the demo accounts' password
    python scripts/k8s_secrets.py --force               # overwrite an existing file

The file is applied by `kubectl apply -f k8s/` together with the other manifests.
Rotating secrets: regenerate with --force, re-apply, then
`kubectl rollout restart deployment/backend -n medicloud`. (The database keeps the password
it was initialised with - rotate it inside PostgreSQL too, or delete the PVC for a fresh DB.)
"""

import argparse
import secrets
import sys
from pathlib import Path

TARGET = Path(__file__).resolve().parent.parent / "k8s" / "01-secrets.yaml"

TEMPLATE = """\
# GENERATED by scripts/k8s_secrets.py - DO NOT COMMIT (git-ignored).
apiVersion: v1
kind: Secret
metadata:
  name: medicloud-secrets
  namespace: medicloud
  labels:
    app.kubernetes.io/part-of: medicloud
type: Opaque
stringData:
  POSTGRES_USER: "medicloud"
  POSTGRES_PASSWORD: "{postgres_password}"
  JWT_SECRET_KEY: "{jwt_secret}"
  SEED_DEMO_PASSWORD: "{demo_password}"
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--demo-password", default="Demo@12345",
                        help="password for the four seeded demo accounts (min 8 chars)")
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    args = parser.parse_args()

    if len(args.demo_password) < 8 or '"' in args.demo_password:
        parser.error("--demo-password must be 8+ characters and contain no double quotes")
    if TARGET.exists() and not args.force:
        print(f"{TARGET} already exists - keeping it (use --force to regenerate).")
        return 0

    TARGET.write_text(
        TEMPLATE.format(
            postgres_password=secrets.token_urlsafe(24),
            jwt_secret=secrets.token_urlsafe(48),
            demo_password=args.demo_password,
        ),
        encoding="utf-8",
    )
    print(f"Wrote {TARGET} (random DB password and JWT key; demo password as requested).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
